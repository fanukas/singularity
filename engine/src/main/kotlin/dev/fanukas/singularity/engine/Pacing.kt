package dev.fanukas.singularity.engine

import kotlin.math.abs
import kotlin.math.exp
import kotlin.math.ln
import kotlin.math.max
import kotlin.math.min

/**
 * The pacing model. The reference player buys like the full crew from the first second; the solver finds the launch
 * cost of every step so that player arrives on the reference curve ([Skeleton.ARRIVAL]). Scenarios never change
 * these numbers, so every scenario paces the same and shares the leaderboards (spec sections 1, 2 and 7).
 */
object Pacing {

    fun tickFor(step: Int) = (Skeleton.STEP_DURATION[min(step, Skeleton.STEPS - 1)] / 2000.0).coerceIn(1.0, 600.0)

    /** Runs the reference player from [start] until it has reached [step] (inclusive); returns the arrival time. */
    fun runUntilArrived(engine: Engine, start: GameState, step: Int, limit: Double, fixedTick: Double? = null): Double {
        val s = start
        while (s.step <= step && s.time < limit) engine.tick(s, fixedTick ?: tickFor(s.step), everyoneAutomates = true)
        return if (s.step > step) s.time else Double.POSITIVE_INFINITY
    }

    /** Solves the launch cost table. Deterministic: the same skeleton always gives the same table. */
    fun solve(log: ((String) -> Unit)? = null): DoubleArray {
        // Unsolved steps cost infinity, so the reference player never launches past the step being solved.
        val costs = DoubleArray(Skeleton.STEPS) { Double.POSITIVE_INFINITY }
        var state = GameState()
        for (k in 0 until Skeleton.STEPS) {
            val target = Skeleton.ARRIVAL[k]
            val limit = target + 3 * Skeleton.STEP_DURATION[k]
            fun arrival(cost: Double): Double {
                costs[k] = cost
                return runUntilArrived(Engine(costs), state.copy(), k, limit)
            }
            val chosen = if (arrival(0.0) >= target) 0.0 else {
                var lo = 0.0
                var hi = max(1.0, state.main)
                while (arrival(hi) < target && hi < 1e300) { lo = hi; hi *= 100.0 }
                repeat(80) {
                    val mid = if (lo <= 0.0) hi / 2 else exp((ln(lo) + ln(hi)) / 2)
                    if (arrival(mid) < target) lo = mid else hi = mid
                }
                hi
            }
            costs[k] = chosen
            val next = state.copy()
            val at = runUntilArrived(Engine(costs), next, k, limit)
            check(at.isFinite()) { "step $k unreachable" }
            log?.invoke("step $k cost %.3g arrived day %.3f (target %.3f)".format(chosen, at / Skeleton.DAY, target / Skeleton.DAY))
            state = next
        }
        return costs
    }

    /** Kotlin source for LaunchTable.kt. */
    fun tableSource(costs: DoubleArray): String = buildString {
        appendLine("package dev.fanukas.singularity.engine")
        appendLine()
        appendLine("/** Generated by Pacing.solve() from the skeleton. Do not edit by hand; regenerate (see README). */")
        appendLine("object LaunchTable {")
        appendLine("    val COSTS = doubleArrayOf(")
        costs.toList().chunked(4).forEach { row -> appendLine("        " + row.joinToString(", ") { it.toString() } + ",") }
        appendLine("    )")
        appendLine("}")
    }

    /** Arrival time of every step for the reference player with the shipped table. */
    fun replay(engine: Engine = Engine(), fixedTick: Double? = null): DoubleArray {
        val s = GameState()
        val out = DoubleArray(Skeleton.STEPS) { Double.POSITIVE_INFINITY }
        for (k in 0 until Skeleton.STEPS) {
            out[k] = runUntilArrived(engine, s, k, Skeleton.ARRIVAL[k] * 2 + Skeleton.DAY, fixedTick)
            if (out[k].isInfinite()) break
        }
        return out
    }

    /** Worst relative miss of [arrivals] against the reference curve (0.05 = 5 %), ignoring sub-minute misses. */
    fun worstMiss(arrivals: DoubleArray): Double {
        var worst = 0.0
        for (k in 0 until Skeleton.STEPS) {
            val miss = abs(arrivals[k] - Skeleton.ARRIVAL[k])
            if (miss > 60.0) worst = max(worst, miss / Skeleton.ARRIVAL[k])
        }
        return worst
    }

    /** Compact report: target and actual day at the end of each layer. */
    fun report(arrivals: DoubleArray): String = buildString {
        for (l in 0 until Skeleton.LAYERS) {
            val k = (l + 1) * Skeleton.STEPS_PER_LAYER - 1
            append("PACING layer ${l + 1}: target day %.1f, reached day %.1f".format(Skeleton.ARRIVAL[k] / Skeleton.DAY, arrivals[k] / Skeleton.DAY))
            appendLine()
        }
        append("PACING first hour: steps reached by 60 min = ${arrivals.count { it <= 3600.0 }}; worst miss %.1f%%".format(worstMiss(arrivals) * 100))
    }
}
